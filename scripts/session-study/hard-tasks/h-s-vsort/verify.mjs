import { spawnSync } from "node:child_process";
const script = join(dir, "vsort.sh");
const run = (input) => {
  const r = spawnSync("bash", [script], { input, encoding: "utf8", cwd: dir, timeout: 20000 });
  return { out: r.stdout, err: r.stderr, status: r.status };
};
