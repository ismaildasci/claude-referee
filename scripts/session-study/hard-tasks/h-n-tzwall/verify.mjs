const { nextOccurrence } = await load("src/occurrence.mjs");
const eq = (t, z, f, want) => assert.equal(nextOccurrence(t, z, f), want, `${t} ${z} ${f}`);
eq("09:00", "America/New_York", "2024-01-15T12:00:00Z", "2024-01-15T14:00:00.000Z");
eq("09:00", "America/New_York", "2024-01-15T14:00:00Z", "2024-01-16T14:00:00.000Z");
eq("09:00", "America/New_York", new Date("2024-01-15T14:00:00.001Z"), "2024-01-16T14:00:00.000Z");
eq("09:00", "America/New_York", "2024-07-15T12:00:00Z", "2024-07-15T13:00:00.000Z");
eq("02:30", "America/New_York", "2024-03-09T12:00:00Z", "2024-03-10T07:30:00.000Z");
eq("02:30", "America/New_York", "2024-03-10T08:00:00Z", "2024-03-11T06:30:00.000Z");
eq("01:30", "America/New_York", "2024-11-02T12:00:00Z", "2024-11-03T05:30:00.000Z");
eq("01:30", "America/New_York", "2024-11-03T05:30:00Z", "2024-11-04T06:30:00.000Z");
eq("01:30", "America/New_York", "2024-11-03T05:00:00Z", "2024-11-03T05:30:00.000Z");
eq("00:00", "Europe/Istanbul", "2024-06-01T20:59:00Z", "2024-06-01T21:00:00.000Z");
eq("01:30", "Europe/London", "2024-03-30T12:00:00Z", "2024-03-31T01:30:00.000Z");
eq("01:30", "Europe/London", "2024-03-31T01:30:00Z", "2024-04-01T00:30:00.000Z");
eq("01:30", "Europe/London", "2024-10-26T12:00:00Z", "2024-10-27T00:30:00.000Z");
eq("01:30", "Europe/London", "2024-10-26T23:30:00Z", "2024-10-27T00:30:00.000Z");
eq("01:30", "Europe/London", "2024-10-27T00:30:00Z", "2024-10-28T01:30:00.000Z");
eq("02:15", "Australia/Lord_Howe", "2024-10-05T00:00:00Z", "2024-10-05T15:45:00.000Z");
eq("01:45", "Australia/Lord_Howe", "2024-04-06T12:00:00Z", "2024-04-06T14:45:00.000Z");
eq("01:45", "Australia/Lord_Howe", "2024-04-06T14:45:00Z", "2024-04-07T15:15:00.000Z");
eq("23:30", "Asia/Kolkata", "2024-01-01T00:00:00Z", "2024-01-01T18:00:00.000Z");
eq("12:00", "Pacific/Auckland", "2024-01-01T00:00:00Z", "2024-01-01T23:00:00.000Z");
for (const bad of ["24:00", "9:00", "09:60", "0900", ""]) assert.throws(() => nextOccurrence(bad, "UTC", "2024-01-01T00:00:00Z"), RangeError, bad);
assert.throws(() => nextOccurrence("09:00", "Mars/Base", "2024-01-01T00:00:00Z"), RangeError);
assert.throws(() => nextOccurrence("09:00", "UTC", "not a date"), RangeError);
