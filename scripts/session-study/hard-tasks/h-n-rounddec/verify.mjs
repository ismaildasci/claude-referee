eq("3.5", 0, "half-even", "4");
eq("-2.5", 0, "half-even", "-2");
eq("2.5", 0, "half-up", "3");
eq("-2.5", 0, "half-up", "-3");
eq("2.5", 0, "half-down", "2");
eq("-2.5", 0, "half-down", "-2");
eq("2.51", 0, "half-down", "3");
eq("-1.2", 0, "floor", "-2");
eq("1.2", 0, "floor", "1");
eq("-1.2", 0, "ceil", "-1");
eq("1.2", 0, "ceil", "2");
eq("-1.9", 0, "trunc", "-1");
eq("1.9", 0, "trunc", "1");
eq("-0.001", 2, "half-even", "0.00");
eq("-0.001", 2, "floor", "-0.01");
eq("-0.001", 2, "ceil", "0.00");
eq("-0.001", 2, "trunc", "0.00");
eq("0.125", 2, "half-even", "0.12");
eq("0.135", 2, "half-even", "0.14");
eq("0.125", 2, "half-up", "0.13");
eq("1.005", 2, "half-up", "1.01");
eq("1.005", 2, "half-even", "1.00");
eq("1", 3, "half-even", "1.000");
eq("12.3", 1, "half-even", "12.3");
eq("5.0", 0, "half-even", "5");
