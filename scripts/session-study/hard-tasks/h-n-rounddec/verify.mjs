for (const bad of ["1e3", "", "abc", "1.", ".5", "+1", "--1", "1 "]) assert.throws(() => roundDecimal(bad, 2, "floor"), TypeError, bad);
assert.throws(() => roundDecimal(5, 2, "floor"), TypeError);
for (const s of [-1, 1.5, "2", NaN]) assert.throws(() => roundDecimal("1.5", s, "floor"), RangeError);
assert.throws(() => roundDecimal("1.5", 0, "round"), RangeError);
