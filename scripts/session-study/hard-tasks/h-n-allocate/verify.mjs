const { allocate } = await load("src/allocate.mjs");
const sum = (a) => a.reduce((x, y) => x + y, 0);
assert.deepEqual(allocate(100, [1, 1, 1]), [34, 33, 33]);
assert.deepEqual(allocate(10, [1, 1, 1, 1]), [3, 3, 2, 2]);
assert.deepEqual(allocate(5, [0, 1, 1]), [0, 3, 2]);
assert.deepEqual(allocate(0, [3, 4]), [0, 0]);
assert.deepEqual(allocate(7, [5]), [7]);
assert.deepEqual(allocate(101, [50, 30, 20]), [51, 30, 20]);
assert.deepEqual(allocate(2, [1, 2, 2]), [0, 1, 1]);
const out = allocate(1000, [1, 2, 3, 4, 5, 6, 7]);
assert.equal(sum(out), 1000);
assert.deepEqual(out, [36, 71, 107, 143, 179, 214, 250]);
const w = [3, 3, 3];
allocate(10, w);
assert.deepEqual(w, [3, 3, 3]);
assert.throws(() => allocate(10, []), RangeError);
assert.throws(() => allocate(10, [0, 0]), RangeError);
assert.throws(() => allocate(-1, [1]), RangeError);
assert.throws(() => allocate(10, [1, -1]), RangeError);
assert.throws(() => allocate(1.5, [1]), RangeError);
assert.throws(() => allocate(10, [1, 0.5]), RangeError);
