const { freeSlots } = await load("src/slots.mjs");
const day = { start: "09:00", end: "17:00" };
const b = (s, e) => ({ start: s, end: e });
assert.deepEqual(freeSlots(day, [], 30), [b("09:00", "17:00")]);
assert.deepEqual(freeSlots(day, [b("10:00", "11:00"), b("13:00", "14:30")], 30), [b("09:00", "10:00"), b("11:00", "13:00"), b("14:30", "17:00")]);
assert.deepEqual(freeSlots(day, [b("09:00", "10:00"), b("10:00", "12:00")], 60), [b("12:00", "17:00")]);
assert.deepEqual(freeSlots(day, [b("09:00", "12:00"), b("10:00", "11:00")], 30), [b("12:00", "17:00")]);
assert.deepEqual(freeSlots(day, [b("13:00", "14:00"), b("09:30", "10:00"), b("13:00", "14:00")], 60), [b("10:00", "13:00"), b("14:00", "17:00")]);
assert.deepEqual(freeSlots(day, [b("08:00", "09:30"), b("16:30", "18:00")], 15), [b("09:30", "16:30")]);
assert.deepEqual(freeSlots(day, [b("06:00", "08:00"), b("18:00", "20:00")], 15), [b("09:00", "17:00")]);
assert.deepEqual(freeSlots(day, [b("10:00", "10:30"), b("10:30", "11:00")], 30), [b("09:00", "10:00"), b("11:00", "17:00")]);
assert.deepEqual(freeSlots(day, [b("09:20", "17:00")], 20), [b("09:00", "09:20")]);
assert.deepEqual(freeSlots(day, [b("09:20", "17:00")], 21), []);
assert.deepEqual(freeSlots(day, [b("09:20", "17:00")], 19), [b("09:00", "09:20")]);
assert.deepEqual(freeSlots({ start: "20:00", end: "24:00" }, [b("21:00", "22:00")], 60), [b("20:00", "21:00"), b("22:00", "24:00")]);
assert.deepEqual(freeSlots(day, [b("08:00", "18:00")], 1), []);
const input = [b("12:00", "13:00"), b("09:00", "10:00")];
freeSlots(day, input, 10);
assert.deepEqual(input, [b("12:00", "13:00"), b("09:00", "10:00")]);
assert.throws(() => freeSlots(day, [b("10:00", "10:00")], 10), RangeError);
assert.throws(() => freeSlots(day, [b("11:00", "10:00")], 10), RangeError);
assert.throws(() => freeSlots(day, [], 0), RangeError);
assert.throws(() => freeSlots(day, [], 2.5), RangeError);
