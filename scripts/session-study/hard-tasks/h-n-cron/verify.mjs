const { nextRun } = await load("src/cron.mjs");
assert.equal(nextRun("*/15 * * * *", "2024-01-01T10:07:30Z"), "2024-01-01T10:15:00.000Z");
assert.equal(nextRun("*/15 * * * *", "2024-01-01T10:15:00Z"), "2024-01-01T10:30:00.000Z");
assert.equal(nextRun("*/15 * * * *", new Date("2024-01-01T10:59:59.999Z")), "2024-01-01T11:00:00.000Z");
assert.equal(nextRun("0 0 1 * 1", "2024-01-01T00:00:00Z"), "2024-01-08T00:00:00.000Z");
assert.equal(nextRun("0 12 15 * 5", "2024-03-01T00:00:00Z"), "2024-03-01T12:00:00.000Z");
assert.equal(nextRun("0 12 15 * 5", "2024-03-14T13:00:00Z"), "2024-03-15T12:00:00.000Z");
assert.equal(nextRun("0 12 15 * 5", "2024-03-15T12:00:00Z"), "2024-03-22T12:00:00.000Z");
assert.equal(nextRun("30 4 * * 7", "2024-01-01T00:00:00Z"), "2024-01-07T04:30:00.000Z");
assert.equal(nextRun("30 4 * * 0", "2024-01-01T00:00:00Z"), "2024-01-07T04:30:00.000Z");
assert.equal(nextRun("0 0 29 2 *", "2023-03-01T00:00:00Z"), "2024-02-29T00:00:00.000Z");
assert.equal(nextRun("0 0 31 2 *", "2024-01-01T00:00:00Z"), null);
assert.equal(nextRun("5 4 * * 1-5/2", "2024-01-02T05:00:00Z"), "2024-01-03T04:05:00.000Z");
assert.equal(nextRun("0 0 * * *", "2024-12-31T23:59:59Z"), "2025-01-01T00:00:00.000Z");
assert.equal(nextRun("1,15,30 * * * *", "2024-01-01T10:15:00Z"), "2024-01-01T10:30:00.000Z");
assert.equal(nextRun("0 9 */10 * *", "2024-01-11T10:00:00Z"), "2024-01-21T09:00:00.000Z");
assert.equal(nextRun("0 0 1 1 *", "2024-06-01T00:00:00Z"), "2025-01-01T00:00:00.000Z");
for (const bad of ["* * * *", "* * * * * *", "60 * * * *", "* 24 * * *", "* * 0 * *", "* * * 13 *", "* * * * 8", "*/0 * * * *", "5-1 * * * *", "a * * * *", "1,,2 * * * *"]) {
  assert.throws(() => nextRun(bad, "2024-01-01T00:00:00Z"), SyntaxError, bad);
}
