assert.throws(() => loadConfig(cfg, "production", { APP_PORT: "abc" }), TypeError);
assert.throws(() => loadConfig(cfg, "production", { APP_DEBUG: "yes" }), TypeError);
assert.throws(() => loadConfig(cfg, "production", { APP_TAGS: "x" }), TypeError);
assert.throws(() => loadConfig(cfg, "production", { APP_TAGS: '{"a":1}' }), TypeError);
const a = { x: { y: [1], z: 1 }, keep: 1 };
const b = { x: { y: [2, 3], z: null, w: { v: 1 } }, add: [1] };
const aCopy = structuredClone(a);
const bCopy = structuredClone(b);
const merged = deepMerge(a, b);
assert.deepEqual(merged, { x: { y: [2, 3], w: { v: 1 } }, keep: 1, add: [1] });
assert.deepEqual(a, aCopy);
assert.deepEqual(b, bCopy);
merged.x.w.v = 2;
merged.add.push(2);
merged.x.y.push(9);
assert.deepEqual(b, bCopy);
assert.deepEqual(deepMerge({ a: { b: 1 } }, { a: [1] }), { a: [1] });
assert.deepEqual(deepMerge({ a: [1] }, { a: { b: 1 } }), { a: { b: 1 } });
assert.deepEqual(deepMerge({ a: 1 }, { a: { b: null } }), { a: {} });
const base = { db: { poolSize: 5, host: "h" }, n: 1, on: false, list: [], s: "x" };
