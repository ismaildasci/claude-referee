assert.deepEqual(res, { db: { poolSize: 7, host: "z", extra: { deep: "q" } }, n: 1.5, on: true, list: [1], s: "5" });
assert.deepEqual(base, baseCopy);
assert.throws(() => applyEnv(base, { APP_N: "" }), TypeError);
assert.throws(() => applyEnv(base, { APP_N: "1x" }), TypeError);
assert.deepEqual(applyEnv(base, { APP_N: " 3 " }).n, 3);
